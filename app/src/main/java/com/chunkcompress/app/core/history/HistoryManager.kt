package com.chunkcompress.app.core.history

import android.content.Context
import com.chunkcompress.app.core.SessionRecord
import com.chunkcompress.app.core.StorageUtils
import com.google.gson.Gson
import com.google.gson.GsonBuilder
import com.google.gson.reflect.TypeToken
import java.io.File
import java.io.FileReader
import java.io.FileWriter
import java.text.SimpleDateFormat
import java.util.Date
import java.util.Locale

class HistoryManager(private val context: Context) {

    private val gson: Gson by lazy {
        GsonBuilder().setPrettyPrinting().create()
    }

    private val historyFile: File
        get() = File(context.filesDir, "history_sessions.json")

    @Synchronized
    fun getSessions(): List<SessionRecord> {
        val file = historyFile
        if (!file.exists() || file.length() == 0L) return emptyList()

        return try {
            FileReader(file).use { reader ->
                val type = object : TypeToken<List<SessionRecord>>() {}.type
                gson.fromJson<List<SessionRecord>>(reader, type) ?: emptyList()
            }
        } catch (e: Exception) {
            emptyList()
        }
    }

    @Synchronized
    fun recordSession(record: SessionRecord) {
        val current = getSessions().toMutableList()
        val index = current.indexOfFirst { it.sessionId == record.sessionId }
        if (index >= 0) {
            current[index] = record
        } else {
            current.add(0, record) // Most recent first
        }

        // Keep last 100 sessions
        val trimmed = if (current.size > 100) current.take(100) else current

        try {
            val tempFile = File(context.filesDir, "history_sessions.json.tmp")
            FileWriter(tempFile).use { writer ->
                gson.toJson(trimmed, writer)
            }
            if (historyFile.exists()) historyFile.delete()
            tempFile.renameTo(historyFile)
        } catch (e: Exception) {
            e.printStackTrace()
        }
    }

    @Synchronized
    fun removeSession(sessionId: String) {
        val current = getSessions().toMutableList()
        val removed = current.removeAll { it.sessionId == sessionId }
        if (removed) {
            try {
                FileWriter(historyFile).use { writer ->
                    gson.toJson(current, writer)
                }
            } catch (e: Exception) {
                e.printStackTrace()
            }
        }
    }

    @Synchronized
    fun clearAllHistory() {
        if (historyFile.exists()) {
            historyFile.delete()
        }
    }

    /**
     * Generates a printable/exportable Markdown summary report for a session.
     */
    fun generateSessionReport(record: SessionRecord): String {
        val dateStr = SimpleDateFormat("yyyy-MM-dd HH:mm:ss", Locale.getDefault()).format(Date(record.timestamp))
        return """
            # ChunkCompress Session Report
            - **Session ID:** `${record.sessionId}`
            - **Date:** $dateStr
            - **Type:** ${if (record.isDecompression) "Decompression / Restoration" else "Incremental Compression"}
            - **Status:** ${record.statusText} (Completed: ${record.isCompleted})
            - **Source Path:** `${record.sourcePath}`
            - **Destination Path:** `${record.destinationPath}`
            - **Total Original Size:** ${StorageUtils.formatBytes(record.totalOriginalBytes)}
            - **Archive Output Size:** ${StorageUtils.formatBytes(record.compressedSizeBytes)}
            - **Space Reclaimed:** ${StorageUtils.formatBytes(record.reclaimedBytes)}
            - **Files Processed:** ${record.totalFiles}
            - **Chunks:** ${record.totalChunks}
            
            Generated by ChunkCompress 2.0
        """.trimIndent()
    }
}
